function language() {
  var locale = 'en';
  try {
    var info = Pebble.getActiveWatchInfo();
    if (info && info.language) {
      locale = String(info.language).toLowerCase().slice(0, 2);
    }
  } catch (e) {
    locale = 'en';
  }
  return catalog[locale] ? locale : 'en';
}

module.exports = {
  get: function() {
    return catalog[language()];
  }
};
